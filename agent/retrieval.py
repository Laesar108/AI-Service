"""Persistent SQLite vector store, exact cosine search for a small runbook corpus.

Vectors are generated by the actual embeddings API, not keyword counts.
Whole short documents preserve conditions/exceptions. No query cache in evaluation.
"""
import asyncio
import hashlib
import json
import math
import os
from pathlib import Path
import sqlite3
import time
import httpx
from .telemetry import record

ROOT = Path(__file__).resolve().parents[1]


class EmbeddingClient:
    def __init__(self, model="text-embedding-3-small"):
        self.model = model

    async def embed(self, texts):
        start = time.perf_counter()
        key = os.environ.get("OPENAI_API_KEY")
        if not key:
            raise RuntimeError("Embedding authentication unavailable")
        try:
            async with httpx.AsyncClient(timeout=90) as client:
                response = await client.post("https://api.openai.com/v1/embeddings",
                    headers={"Authorization": f"Bearer {key}"},
                    json={"model": self.model, "input": texts, "encoding_format": "float"})
                response.raise_for_status()
                body = response.json()
        except Exception as exc:
            raise RuntimeError(f"Embedding request failed ({type(exc).__name__})") from None
        tokens = body["usage"]["total_tokens"]
        record(self.model, {"tokens": tokens, "input_tokens": tokens,
                           "output_tokens": 0, "cached_input_tokens": 0},
               time.perf_counter()-start, kind="embedding", items=len(texts))
        return [r["embedding"] for r in sorted(body["data"], key=lambda r: r["index"])]


def normalize(vector):
    norm = math.sqrt(sum(x*x for x in vector))
    if not norm or not all(math.isfinite(x) for x in vector):
        raise ValueError("Invalid embedding")
    return [x/norm for x in vector]


# [PDF 1] 키워드 매핑을 대체할 의미 검색기. 문서/유형 메타데이터와 벡터를 SQLite에 저장한다.
# 전용 대규모 벡터 검색 엔진 대신 소규모 Runbook의 유사도를 직접 계산하는 구현이다.
class RunbookRetriever:
    def __init__(self, corpus=None, db=None, embedder=None, *, top_k=3, threshold=0.30, margin=0.10):
        self.corpus = Path(corpus or ROOT/"data/runbooks")
        self.db = Path(db or ROOT/"data/runbook_vectors.sqlite3")
        self.embedder = embedder or EmbeddingClient()
        self.top_k, self.threshold, self.margin = top_k, threshold, margin
        self._lock = asyncio.Lock()
        self._signature = None

    def documents(self):
        return [{"id": p.stem, "incident_type": p.stem, "source": p.name,
                 "text": p.read_text(), "version": hashlib.sha256(p.read_bytes()).hexdigest()}
                for p in sorted(self.corpus.glob("*.md"))]

    def connect(self):
        self.db.parent.mkdir(parents=True, exist_ok=True)
        db = sqlite3.connect(self.db)
        db.execute("""CREATE TABLE IF NOT EXISTS vectors
                      (id TEXT PRIMARY KEY, model TEXT, version TEXT, metadata TEXT, vector TEXT)""")
        return db

    # [임베딩 비용 관리] 문서 해시와 모델을 비교해 변경된 문서만 다시 임베딩한다.
    async def ensure_index(self):
        async with self._lock:
            docs = self.documents()
            if not docs:
                raise ValueError("Empty runbook corpus")
            signature = (self.embedder.model, tuple((d["id"], d["version"]) for d in docs))
            if signature == self._signature:
                return
            with self.connect() as db:
                existing = {r[0]: (r[1],r[2]) for r in db.execute("SELECT id,model,version FROM vectors")}
            changed = [d for d in docs if existing.get(d["id"]) != (self.embedder.model,d["version"])]
            vectors = await self.embedder.embed([d["text"] for d in changed]) if changed else []
            if len(vectors) != len(changed):
                raise ValueError("Embedding count mismatch")
            with self.connect() as db:
                for d, vector in zip(changed, vectors):
                    db.execute("INSERT OR REPLACE INTO vectors VALUES (?,?,?,?,?)",
                               (d["id"],self.embedder.model,d["version"],
                                json.dumps(d,ensure_ascii=False),json.dumps(normalize(vector))))
                for removed in set(existing)-{d["id"] for d in docs}:
                    db.execute("DELETE FROM vectors WHERE id=?", (removed,))
            self._signature = signature

    async def rank(self, queries):
        await self.ensure_index()
        query_vectors = await self.embedder.embed(queries)
        with self.connect() as db:
            rows = [(json.loads(m),json.loads(v)) for m,v in db.execute(
                "SELECT metadata,vector FROM vectors WHERE model=?", (self.embedder.model,))]
        ranked = []
        for query in query_vectors:
            unit = normalize(query)
            if any(len(unit) != len(v) for _,v in rows):
                raise ValueError("Embedding dimension mismatch")
            ranked.append(sorted(
                [{**m,"score":sum(a*b for a,b in zip(unit,v))} for m,v in rows],
                key=lambda d: (-d["score"],d["id"])))
        return ranked

    # [검색 품질 관리] 개발 질문에서 선택한 임계값·순위 제한으로 무관한 문서 유입을 줄인다.
    def select(self, ranked):
        if not ranked or ranked[0]["score"] < self.threshold:
            return []
        cutoff = max(self.threshold, ranked[0]["score"]-self.margin)
        return [d for d in ranked[:self.top_k] if d["score"] >= cutoff]

    # [다중 Runbook] 검색어별 후보를 합치고 중복 제거한다. 검색어당 top_k=1이어도
    # 질문과 관측 알림별 결과를 합치면 여러 문서를 확보할 수 있다.
    async def search(self, queries):
        rankings = await self.rank(queries)
        unique = {}
        for ranking in rankings:
            for doc in self.select(ranking):
                if doc["id"] not in unique or doc["score"] > unique[doc["id"]]["score"]:
                    unique[doc["id"]] = doc
        return sorted(unique.values(), key=lambda d: (-d["score"],d["id"]))


def configured_retriever(corpus=None, db=None):
    config_path = ROOT/"data/retrieval_config.json"
    config = json.loads(config_path.read_text()) if config_path.exists() else {}
    return RunbookRetriever(corpus, db, EmbeddingClient(config.get("model","text-embedding-3-small")),
                           **{k:config[k] for k in ("top_k","threshold","margin") if k in config})
